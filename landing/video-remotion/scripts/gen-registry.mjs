// Scan videos/<slug>/ for complete video bundles and (re)generate src/videos.gen.ts.
// A bundle is "complete" when it has scenes.json + beats.json + timings.json + outro.json.
// Optional: customs.tsx (a CUSTOMS map) for one-off bespoke visuals.
// Each agent only creates its own videos/<slug>/ dir; run this once before render — zero shared-file edits.
import {readdirSync, statSync, existsSync, writeFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
import {dirname, join} from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const videosDir = join(root, "videos");
const REQUIRED = ["scenes.json", "beats.json", "timings.json", "outro.json"];

const slugs = readdirSync(videosDir)
  .filter((name) => {
    const p = join(videosDir, name);
    if (!statSync(p).isDirectory()) return false;
    const missing = REQUIRED.filter((f) => !existsSync(join(p, f)));
    if (missing.length) {
      console.warn(`skip "${name}" — missing ${missing.join(", ")}`);
      return false;
    }
    return true;
  })
  .sort();

const id = (slug) => slug.replace(/[^a-zA-Z0-9]/g, "_");
const hasCustoms = (slug) => existsSync(join(videosDir, slug, "customs.tsx"));

const imports = slugs
  .map((slug) => {
    const v = id(slug);
    const lines = [
      `import scenes_${v} from "../videos/${slug}/scenes.json";`,
      `import beats_${v} from "../videos/${slug}/beats.json";`,
      `import timings_${v} from "../videos/${slug}/timings.json";`,
      `import outroData_${v} from "../videos/${slug}/outro.json";`,
    ];
    if (hasCustoms(slug)) lines.push(`import {CUSTOMS as customs_${v}} from "../videos/${slug}/customs";`);
    return lines.join("\n");
  })
  .join("\n");

const entries = slugs
  .map((slug) => {
    const v = id(slug);
    return `  {
    slug: "${slug}",
    scenes: scenes_${v} as Record<string, BeatData>,
    customs: ${hasCustoms(slug) ? `customs_${v}` : "{}"},
    beats: beats_${v} as Beat[],
    timings: timings_${v} as Record<string, Line[]>,
    outro: outroData_${v} as {audio: string; durationInFrames: number},
  },`;
  })
  .join("\n");

const out = `// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit by hand.
// Run: node scripts/gen-registry.mjs
import type React from "react";
import type {BeatData} from "./kit";
${imports}

export type Beat = {id: string; audio: string; durationInFrames: number; durationSec?: number};
export type Word = {w: string; s: number; e: number};
export type Line = {text: string; start: number; end: number; words: Word[]};
export type VideoEntry = {
  slug: string;
  scenes: Record<string, BeatData>;
  customs: Record<string, React.FC>;
  beats: Beat[];
  timings: Record<string, Line[]>;
  outro: {audio: string; durationInFrames: number};
};

export const VIDEOS: VideoEntry[] = [
${entries}
];
`;

writeFileSync(join(root, "src", "videos.gen.ts"), out, "utf-8");
console.log(`wrote src/videos.gen.ts with ${slugs.length} video(s): ${slugs.join(", ")}`);
